package output

import (
	"fmt"
	"strings"

	sgraph "github.com/vhco-pro/stackgraph/pkg/graph"
)

// RenderHTML produces a self-contained interactive HTML page: the laid-out SVG
// with pan/zoom, a click-to-inspect side panel fed by the embedded graph JSON,
// and automatic dark mode. No external requests — everything is inline.
func RenderHTML(g *sgraph.Graph) ([]byte, error) {
	svg, err := RenderSVG(g)
	if err != nil {
		return nil, fmt.Errorf("failed to render embedded SVG: %w", err)
	}

	graphJSON, err := g.ToJSON()
	if err != nil {
		return nil, fmt.Errorf("failed to serialize graph JSON: %w", err)
	}
	// </script> inside a JSON string would terminate the script block early
	safeJSON := strings.ReplaceAll(string(graphJSON), "</", `<\/`)

	title := "Infrastructure Diagram"
	if g.Metadata != nil && g.Metadata.Provider != "" {
		title = g.Metadata.Provider + " — " + title
	}

	var b strings.Builder
	b.WriteString("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
	b.WriteString(`<meta name="viewport" content="width=device-width, initial-scale=1">` + "\n")
	fmt.Fprintf(&b, "<title>%s</title>\n", escapeXMLStr(title))
	// Page chrome shares the SVG renderer's palette so the canvas never floats
	// on a mismatched ground when the dark theme is retuned.
	fmt.Fprintf(&b, `<style>
  :root { --bg: %s; --panel: #F8F9FA; --border: %s; --text: %s; --muted: #6C757D; --accent: %s; }
  @media (prefers-color-scheme: dark) {
    :root { --bg: %s; --panel: #22223A; --border: %s; --text: %s; --muted: %s; --accent: %s; }
  }`, paletteLightBG, paletteLightBorder, paletteLightText, paletteLightFlow,
		paletteDarkBG, paletteDarkBorder, paletteDarkText, paletteDarkEdge, paletteDarkFlow)
	b.WriteString(`
  * { box-sizing: border-box; }
  body { margin: 0; height: 100vh; display: flex; flex-direction: column; background: var(--bg); color: var(--text);
         font-family: system-ui, sans-serif; overflow: hidden; }
  header { display: flex; align-items: center; gap: 12px; padding: 8px 14px; border-bottom: 1px solid var(--border); flex: none; }
  header h1 { font-size: 14px; margin: 0; font-weight: 600; }
  header .meta { color: var(--muted); font-size: 12px; }
  header input { margin-left: auto; background: var(--panel); color: var(--text); border: 1px solid var(--border);
                 border-radius: 6px; padding: 5px 10px; font-size: 12px; width: 220px; }
  main { flex: 1; display: flex; min-height: 0; }
  #viewport { flex: 1; overflow: hidden; cursor: grab; position: relative; }
  #viewport.panning { cursor: grabbing; }
  #canvas { transform-origin: 0 0; position: absolute; }
  #canvas svg .sg-node { cursor: pointer; }
  #canvas svg .sg-node.dim { opacity: 0.25; }
  #canvas svg .sg-node.hit rect, #canvas svg [data-id].hit { outline: 2px solid var(--accent); }
  aside { width: 300px; flex: none; border-left: 1px solid var(--border); background: var(--panel);
          padding: 14px; overflow-y: auto; display: none; }
  aside.open { display: block; }
  aside h2 { font-size: 13px; margin: 0 0 2px; word-break: break-all; }
  aside .type { color: var(--muted); font-size: 12px; margin-bottom: 10px; word-break: break-all; }
  aside table { width: 100%; border-collapse: collapse; font-size: 12px; }
  aside td { padding: 4px 6px 4px 0; vertical-align: top; border-bottom: 1px solid var(--border); word-break: break-all; }
  aside td:first-child { color: var(--muted); white-space: nowrap; }
  aside .close { float: right; cursor: pointer; border: none; background: none; color: var(--muted); font-size: 16px; }
  footer { padding: 5px 14px; border-top: 1px solid var(--border); color: var(--muted); font-size: 11px; flex: none; }
  kbd { background: var(--panel); border: 1px solid var(--border); border-radius: 3px; padding: 0 4px; }
</style>
</head>
<body>
<header>
  <h1>` + escapeXMLStr(title) + `</h1>
  <span class="meta" id="counts"></span>
  <input id="search" type="search" placeholder="Filter resources…" aria-label="Filter resources">
</header>
<main>
  <div id="viewport"><div id="canvas">
`)
	b.Write(svg)
	b.WriteString(`</div></div>
  <aside id="panel" aria-live="polite"></aside>
</main>
<footer>Scroll to zoom · drag to pan · click a resource for details · <kbd>0</kbd> reset view · generated by stackgraph</footer>
<script type="application/json" id="graph-data">`)
	b.WriteString(safeJSON)
	b.WriteString(`</script>
<script>
(function () {
  var graph = JSON.parse(document.getElementById('graph-data').textContent);
  var nodesById = {};
  graph.nodes.forEach(function (n) { nodesById[n.id] = n; });
  document.getElementById('counts').textContent =
    graph.nodes.length + ' resources · ' + (graph.edges || []).length + ' edges';

  var viewport = document.getElementById('viewport');
  var canvas = document.getElementById('canvas');
  var panel = document.getElementById('panel');
  var scale = 1, tx = 20, ty = 20;

  function apply() { canvas.style.transform = 'translate(' + tx + 'px,' + ty + 'px) scale(' + scale + ')'; }
  apply();

  viewport.addEventListener('wheel', function (e) {
    e.preventDefault();
    var rect = viewport.getBoundingClientRect();
    var mx = e.clientX - rect.left, my = e.clientY - rect.top;
    var factor = e.deltaY < 0 ? 1.15 : 1 / 1.15;
    var next = Math.min(8, Math.max(0.1, scale * factor));
    tx = mx - (mx - tx) * (next / scale);
    ty = my - (my - ty) * (next / scale);
    scale = next;
    apply();
  }, { passive: false });

  // Pan on drag; a release with less than 5px of travel counts as a click and
  // opens the details panel for the resource under the pointer. Pointer capture
  // retargets events to the viewport, so clicks are resolved by hit-testing.
  var panning = false, px = 0, py = 0, dragDistance = 0;
  viewport.addEventListener('pointerdown', function (e) {
    panning = true; px = e.clientX; py = e.clientY; dragDistance = 0;
    viewport.classList.add('panning');
    viewport.setPointerCapture(e.pointerId);
  });
  viewport.addEventListener('pointermove', function (e) {
    if (!panning) return;
    dragDistance += Math.abs(e.clientX - px) + Math.abs(e.clientY - py);
    tx += e.clientX - px; ty += e.clientY - py;
    px = e.clientX; py = e.clientY;
    apply();
  });
  viewport.addEventListener('pointerup', function (e) {
    panning = false;
    viewport.classList.remove('panning');
    if (dragDistance > 5) return; // was a pan, not a click
    var hit = document.elementFromPoint(e.clientX, e.clientY);
    var el = hit && hit.closest ? hit.closest('[data-id]') : null;
    if (!el) {
      // Clicking an edge (its tooltip invites it) keeps the panel open;
      // only a true background click dismisses it.
      var cls = hit && hit.getAttribute ? (hit.getAttribute('class') || '') : '';
      if (cls.indexOf('sg-edge') === -1) panel.classList.remove('open');
      return;
    }
    var node = nodesById[el.getAttribute('data-id')];
    if (node) showPanel(node);
  });

  document.addEventListener('keydown', function (e) {
    if (e.key === '0' && document.activeElement.tagName !== 'INPUT') { scale = 1; tx = 20; ty = 20; apply(); }
  });

  function showPanel(node) {
    var rows = '';
    function row(k, v) {
      if (v === undefined || v === null || v === '') return;
      var e = function (s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;'); };
      rows += '<tr><td>' + e(k) + '</td><td>' + e(v) + '</td></tr>';
    }
    row('service', node.service);
    row('category', node.category);
    row('provider', node.provider);
    row('module', node.module);
    row('parent', node.parent);
    row('count', node.count > 1 ? node.count : '');
    row('action', node.action);
    if (node.attributes) {
      Object.keys(node.attributes).sort().forEach(function (k) {
        var v = node.attributes[k];
        row(k, typeof v === 'object' ? JSON.stringify(v) : v);
      });
    }
    var esc = function (s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;'); };
    panel.innerHTML = '<button class="close" aria-label="Close">×</button><h2>' + esc(node.id) +
      '</h2><div class="type">' + esc(node.resource_type) + '</div><table>' + rows + '</table>';
    panel.classList.add('open');
    panel.querySelector('.close').onclick = function () { panel.classList.remove('open'); };
  }

  // Search filter: dims non-matching leaf nodes; edges dim wholesale while a
  // query is active so full-brightness lines don't drown the matches.
  document.getElementById('search').addEventListener('input', function (e) {
    var q = e.target.value.toLowerCase();
    canvas.querySelectorAll('.sg-node').forEach(function (el) {
      var id = (el.getAttribute('data-id') || '').toLowerCase();
      var node = nodesById[el.getAttribute('data-id')] || {};
      var hay = id + ' ' + (node.service || '') + ' ' + (node.label || '');
      el.classList.toggle('dim', q !== '' && hay.toLowerCase().indexOf(q) === -1);
    });
    canvas.querySelectorAll('path[class^="sg-edge"]').forEach(function (el) {
      el.style.opacity = q === '' ? '' : '0.15';
    });
  });
})();
</script>
</body>
</html>
`)

	return []byte(b.String()), nil
}
